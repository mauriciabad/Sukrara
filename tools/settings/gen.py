"""Generates the settings spec code from THE schema, spikes/settings/settings.json (Python 3.9 stdlib only).

    python3 tools/settings/gen.py           write the generated files
    python3 tools/settings/gen.py --check   exit 1 when a generated file is stale (tools/check rule 'settings')

Outputs: Android SettingsSpec.kt (app.mauri.sukrara.settings) and Mac SettingsSpec.swift (widgets-macos/Shared,
symlinked into the menubar app's sources). Both carry the number formats ('numbers') as NumberSpec values and the
inventory ('settings') as SettingInfo rows, so the number inputs, the models' validation and the schema tests read
the same values on both platforms.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SCHEMA = os.path.join(ROOT, "spikes/settings/settings.json")
KT = os.path.join(ROOT, "spikes/showcase-android/app/src/main/kotlin/app/mauri/sukrara/settings/SettingsSpec.kt")
SWIFT = os.path.join(ROOT, "spikes/widgets-macos/Shared/SettingsSpec.swift")

HEADER = ("CGM research spikes — https://github.com/mauriciabad/cgm-reading-mac-spike\n"
          "Copyright (C) 2026 Maurici Abad\n"
          "SPDX-License-Identifier: GPL-3.0-or-later\n")
NOTE = "GENERATED by tools/settings/gen.py from spikes/settings/settings.json. Do not edit: change the schema and run it."


def load():
    with open(SCHEMA) as f:
        return json.load(f)


def num(v):
    """A JSON number as a Double literal both languages read the same way."""
    f = float(v)
    return repr(f) if f != int(f) else "%d.0" % int(f)


def kstr(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def sstr(s):
    return json.dumps(s, ensure_ascii=False)


def const_kt(name):
    out = ""
    for i, c in enumerate(name):
        if c.isupper() and i:
            out += "_"
        out += c.upper()
    return out


def spec_fields(n):
    return dict(unit=n["unit"], min=n["min"], max=n["max"], step=n["step"], nudge=n.get("nudge", n["step"]),
                scale=n.get("scale", 1), decimals=n.get("decimals", 0), presets=n.get("presets", []),
                default=n["default"], special=n.get("special", {}), custom=n.get("custom", True),
                maxItems=n.get("maxItems", 0))


def platform_key(s, p):
    v = s.get(p)
    return "" if not v else "%s:%s" % (v["store"], v["key"])


def kotlin(schema):
    L = ["// " + l for l in HEADER.splitlines()]
    L += ["// " + NOTE, "package app.mauri.sukrara.settings", "", "import kotlin.math.abs", "import kotlin.math.roundToLong", ""]
    L += [
        "/**",
        " * A number setting's format (spikes/settings/settings.json \"numbers\"), in stored units: valid = a preset, a special",
        " * value (shown by its word, e.g. 0 = \"Off\"), or, when [custom], a value in [min]..[max] on [step]. [scale] = stored",
        " * units per shown unit (ring periods: seconds stored, days shown); [nudge] = one stepper click.",
        " */",
        "data class NumberSpec(",
        "    val id: String, val unit: String, val min: Double, val max: Double, val step: Double, val nudge: Double,",
        "    val scale: Double, val decimals: Int, val presets: List<Double>, val default: Double,",
        "    val special: Map<Double, String>, val custom: Boolean, val maxItems: Int,",
        ") {",
        "    fun inRange(v: Double) = v >= min - EPS && v <= max + EPS",
        "    fun onStep(v: Double): Boolean { val k = (v - min) / step; return abs(k - k.roundToLong()) < 1e-6 }",
        "    /** Whether [v] (stored units) is a value this setting accepts. */",
        "    fun valid(v: Double): Boolean = presets.any { abs(it - v) < EPS } || special.keys.any { abs(it - v) < EPS } ||",
        "        (custom && inRange(v) && onStep(v))",
        "    /** [v] if valid, else the nearest custom value (or [default] when there are no custom values). */",
        "    fun coerce(v: Double): Double = when {",
        "        valid(v) -> v",
        "        !custom || v.isNaN() -> default",
        "        else -> (min + ((v.coerceIn(min, max) - min) / step).roundToLong() * step).coerceIn(min, max)",
        "    }",
        "    /** A stored value as typed / shown, without the unit: \"12\", \"2.5\", \"30\" (days for a ring period). */",
        "    fun text(v: Double): String = (v / scale).let { if (decimals == 0) it.roundToLong().toString() else \"%.${decimals}f\".format(it) }",
        "    /** Typed text (shown units, '.' or ',') → the stored value, or null when it isn't a value in range on step. */",
        "    fun parse(s: String): Double? {",
        "        val shown = s.trim().replace(',', '.').toDoubleOrNull() ?: return null",
        "        val v = shown * scale",
        "        return v.takeIf { custom && inRange(it) && onStep(it) }",
        "    }",
        "    /** The word of a special value (\"off\", \"once\", …) or null. */",
        "    fun specialOf(v: Double): String? = special.entries.firstOrNull { abs(it.key - v) < EPS }?.value",
        "    fun isPreset(v: Double) = presets.any { abs(it - v) < EPS }",
        "    private companion object { const val EPS = 1e-9 }",
        "}",
        "",
        "/** One row of the settings inventory: where it's stored on each platform (\"\" = not on that platform). */",
        "data class SettingInfo(val id: String, val type: String, val number: String?, val mirror: Boolean, val wire: String?,",
        "                       val android: String, val mac: String, val only: String?, val reason: String?)",
        "",
        "/** The schema's number formats and inventory. */",
        "object SettingsSpec {",
    ]
    for name, n in schema["numbers"].items():
        f = spec_fields(n)
        special = ", ".join("%s to %s" % (num(k), kstr(v)) for k, v in f["special"].items())
        L.append("    val %s = NumberSpec(%s, %s, %s, %s, %s, %s, %s, %d, listOf(%s), %s, mapOf(%s), %s, %d)" % (
            const_kt(name), kstr(name), kstr(f["unit"]), num(f["min"]), num(f["max"]), num(f["step"]), num(f["nudge"]),
            num(f["scale"]), f["decimals"], ", ".join(num(p) for p in f["presets"]), num(f["default"]), special,
            "true" if f["custom"] else "false", f["maxItems"]))
    L.append("")
    L.append("    val NUMBERS: Map<String, NumberSpec> = mapOf(%s)" % ", ".join(
        "%s to %s" % (kstr(k), const_kt(k)) for k in schema["numbers"]))
    L.append("")
    L.append("    /** Option lists both platforms offer, in order (schema \"options\"). */")
    L.append("    val OPTIONS: Map<String, List<String>> = mapOf(%s)" % ", ".join(
        "%s to listOf(%s)" % (kstr(k), ", ".join(kstr(v) for v in o["values"])) for k, o in schema.get("options", {}).items() if not k.startswith("_")))
    L.append("")
    L.append("    val SETTINGS: List<SettingInfo> = listOf(")
    for s in schema["settings"]:
        only = s.get("only") or {}
        L.append("        SettingInfo(%s, %s, %s, %s, %s, %s, %s, %s, %s)," % (
            kstr(s["id"]), kstr(s["type"]), kstr(s["number"]) if s.get("number") else "null",
            "true" if s.get("mirror") else "false", kstr(s["wire"]) if s.get("wire") else "null",
            kstr(platform_key(s, "android")), kstr(platform_key(s, "mac")),
            kstr(only["platform"]) if only else "null", kstr(only["reason"]) if only else "null"))
    L.append("    )")
    L.append("}")
    return "\n".join(L) + "\n"


def lower_camel(name):
    return name[0].lower() + name[1:]


def swift(schema):
    L = ["// " + l for l in HEADER.splitlines()]
    L += ["// " + NOTE, "import Foundation", ""]
    L += [
        "/// A number setting's format (spikes/settings/settings.json \"numbers\"), in stored units: valid = a preset, a special",
        "/// value (shown by its word, e.g. 0 = \"Off\"), or, when `custom`, a value in `min`...`max` on `step`. `scale` = stored",
        "/// units per shown unit (ring periods: seconds stored, days shown); `nudge` = one stepper click.",
        "struct NumberSpec: Equatable, Sendable {",
        "    let id: String, unit: String, min: Double, max: Double, step: Double, nudge: Double",
        "    let scale: Double, decimals: Int, presets: [Double], `default`: Double",
        "    let special: [Double: String], custom: Bool, maxItems: Int",
        "    private static let eps = 1e-9",
        "",
        "    func inRange(_ v: Double) -> Bool { v >= min - Self.eps && v <= max + Self.eps }",
        "    func onStep(_ v: Double) -> Bool { let k = (v - min) / step; return abs(k - k.rounded()) < 1e-6 }",
        "    /// Whether `v` (stored units) is a value this setting accepts.",
        "    func valid(_ v: Double) -> Bool {",
        "        presets.contains { abs($0 - v) < Self.eps } || special.keys.contains { abs($0 - v) < Self.eps } || (custom && inRange(v) && onStep(v))",
        "    }",
        "    /// `v` if valid, else the nearest custom value (or `default` when there are no custom values).",
        "    func coerce(_ v: Double) -> Double {",
        "        if valid(v) { return v }",
        "        if !custom || v.isNaN { return `default` }",
        "        return Swift.min(Swift.max(min + ((Swift.min(Swift.max(v, min), max) - min) / step).rounded() * step, min), max)",
        "    }",
        "    /// A stored value as typed / shown, without the unit: \"12\", \"2.5\", \"30\" (days for a ring period).",
        "    func text(_ v: Double) -> String { decimals == 0 ? String(Int((v / scale).rounded())) : String(format: \"%.\\(decimals)f\", v / scale) }",
        "    /// Typed text (shown units, '.' or ',') → the stored value, or nil when it isn't a value in range on step.",
        "    func parse(_ s: String) -> Double? {",
        "        guard let shown = Double(s.trimmingCharacters(in: .whitespaces).replacingOccurrences(of: \",\", with: \".\")) else { return nil }",
        "        let v = shown * scale",
        "        return custom && inRange(v) && onStep(v) ? v : nil",
        "    }",
        "    /// The word of a special value (\"off\", \"once\", …) or nil.",
        "    func specialOf(_ v: Double) -> String? { special.first { abs($0.key - v) < Self.eps }?.value }",
        "    func isPreset(_ v: Double) -> Bool { presets.contains { abs($0 - v) < Self.eps } }",
        "}",
        "",
        "/// One row of the settings inventory: where it's stored on each platform (\"\" = not on that platform).",
        "struct SettingInfo: Sendable {",
        "    let id: String, type: String, number: String?, mirror: Bool, wire: String?, android: String, mac: String, only: String?, reason: String?",
        "}",
        "",
        "/// The schema's number formats and inventory.",
        "enum SettingsSpec {",
    ]
    for name, n in schema["numbers"].items():
        f = spec_fields(n)
        special = ", ".join("%s: %s" % (num(k), sstr(v)) for k, v in f["special"].items()) or ":"
        L.append("    static let %s = NumberSpec(id: %s, unit: %s, min: %s, max: %s, step: %s, nudge: %s, scale: %s, decimals: %d, presets: [%s], default: %s, special: [%s], custom: %s, maxItems: %d)" % (
            lower_camel(name), sstr(name), sstr(f["unit"]), num(f["min"]), num(f["max"]), num(f["step"]), num(f["nudge"]),
            num(f["scale"]), f["decimals"], ", ".join(num(p) for p in f["presets"]), num(f["default"]), special,
            "true" if f["custom"] else "false", f["maxItems"]))
    L.append("")
    L.append("    static let numbers: [String: NumberSpec] = [%s]" % ", ".join(
        "%s: %s" % (sstr(k), lower_camel(k)) for k in schema["numbers"]))
    L.append("")
    L.append("    /// Option lists both platforms offer, in order (schema \"options\").")
    L.append("    static let options: [String: [String]] = [%s]" % (", ".join(
        "%s: [%s]" % (sstr(k), ", ".join(sstr(v) for v in o["values"])) for k, o in schema.get("options", {}).items() if not k.startswith("_")) or ":"))
    L.append("")
    L.append("    static let settings: [SettingInfo] = [")
    for s in schema["settings"]:
        only = s.get("only") or {}
        L.append("        SettingInfo(id: %s, type: %s, number: %s, mirror: %s, wire: %s, android: %s, mac: %s, only: %s, reason: %s)," % (
            sstr(s["id"]), sstr(s["type"]), sstr(s["number"]) if s.get("number") else "nil",
            "true" if s.get("mirror") else "false", sstr(s["wire"]) if s.get("wire") else "nil",
            sstr(platform_key(s, "android")), sstr(platform_key(s, "mac")),
            sstr(only["platform"]) if only else "nil", sstr(only["reason"]) if only else "nil"))
    L.append("    ]")
    L.append("}")
    return "\n".join(L) + "\n"


def outputs():
    s = load()
    return {KT: kotlin(s), SWIFT: swift(s)}


def stale():
    """Paths (repo-relative) whose content differs from what the schema generates."""
    bad = []
    for path, text in outputs().items():
        try:
            with open(path) as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != text:
            bad.append(os.path.relpath(path, ROOT))
    return bad


def main(argv):
    if "--check" in argv:
        bad = stale()
        for b in bad:
            print("stale: %s (run python3 tools/settings/gen.py)" % b)
        return 1 if bad else 0
    for path, text in outputs().items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
