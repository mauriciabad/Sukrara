package app.mauri.sukrara.integrations.export

import app.mauri.sukrara.core.model.Reading
import app.mauri.sukrara.core.model.TreatmentKind
import app.mauri.sukrara.core.model.TreatmentOrigin
import app.mauri.sukrara.core.model.storage.TreatmentRecord
import app.mauri.sukrara.integrations.CurrentSensor
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.doubleOrNull
import java.time.Instant
import java.time.ZoneId
import java.time.ZoneOffset
import java.util.Locale
import kotlin.math.abs
import kotlin.math.roundToLong

/**
 * Readings and treatments as one CSV in LibreView's "Glucose Data" layout (`contracts/export`): the file Tidepool
 * Uploader's LibreView import and Juggluco's export read and write, plus three columns of our own at the end (ISO 8601
 * time with offset, trend, who entered a treatment) and the pen priming column. The Mac writes the same bytes.
 *
 * - One row per reading, at most one every 5 minutes (≥ [MIN_GAP_S] apart), so a reader that counts rows as 5-minute
 *   samples isn't skewed by the 1-minute stream. Rows are oldest first; readings before treatments at the same time.
 * - Device Timestamp is local time without an offset (year first); "Time (ISO 8601)" carries the offset, so the
 *   repeated hour when the clocks go back stays apart.
 * - No person's name anywhere: "Generated by" is the app, "Entered By" is the device kind (phone | mac | follower).
 * - RFC 4180 quoting; a note that starts like a formula (= + - @) gets a leading `'` so a spreadsheet shows it as text.
 */
object GlucoseCsv {
    const val MIME = "text/csv"
    const val MIN_GAP_S = 280L
    private const val MGDL_PER_MMOL = 18.0182
    private const val COLUMNS = 23

    fun header(mmol: Boolean): List<String> {
        val u = if (mmol) "mmol/L" else "mg/dL"
        return listOf(
            "Device",
            "Serial Number",
            "Device Timestamp",
            "Record Type",
            "Historic Glucose $u",
            "Scan Glucose $u",
            "Non-numeric Rapid-Acting Insulin",
            "Rapid-Acting Insulin (units)",
            "Non-numeric Food",
            "Carbohydrates (grams)",
            "Carbohydrates (servings)",
            "Non-numeric Long-Acting Insulin",
            "Long-Acting Insulin (units)",
            "Notes",
            "Strip Glucose $u",
            "Ketone mmol/L",
            "Meal Insulin (units)",
            "Correction Insulin (units)",
            "User Change Insulin (units)",
            "Time (ISO 8601)",
            "Trend (mg/dL/min)",
            "Entered By",
            "Primed Insulin (units)",
        )
    }

    /**
     * The CSV for times in [[from], [to]), CRLF line ends. Deleted treatments (tombstones) and those outside the period
     * are skipped.
     */
    fun write(
        readings: List<Reading>,
        treatments: List<TreatmentRecord>,
        from: Instant,
        to: Instant,
        zone: ZoneId,
        generatedAt: Instant,
        sensor: CurrentSensor? = null,
        mmol: Boolean = false,
    ): String {
        fun serial(t: Instant) = sensor?.takeIf { it.serial.isNotEmpty() && t >= it.start && t < it.end }?.serial.orEmpty()

        fun base(
            t: Instant,
            type: String,
        ) = Array(COLUMNS) { "" }.also {
            it[0] = "Sukrara"
            it[1] = serial(t)
            it[2] = local(t, zone)
            it[3] = type
            it[19] = iso(t, zone)
        }

        class Line(val t: Instant, val order: Int, val id: String, val f: Array<String>)
        val lines = ArrayList<Line>()
        for (r in thin(readings, from, to)) {
            val f = base(r.t, "0")
            f[4] = if (mmol) tenths(r.mgdl / MGDL_PER_MMOL) else r.mgdl.toString()
            f[20] = r.rateMgdlPerMin?.let(::tenths).orEmpty()
            lines += Line(r.t, 0, "", f)
        }
        for (rec in treatments) {
            val tr = rec.treatment
            if (tr.deleted || tr.at < from || tr.at >= to) continue
            val f =
                when (tr.kind) {
                    TreatmentKind.RapidInsulin -> base(tr.at, "4").also { it[7] = tenths(tr.amount) }
                    TreatmentKind.LongInsulin -> base(tr.at, "4").also { it[12] = tenths(tr.amount) }
                    TreatmentKind.Carbs -> base(tr.at, "5").also { it[9] = Math.round(tr.amount).toString() }
                    TreatmentKind.Note -> base(tr.at, "6")
                }
            f[13] = textCell(tr.note)
            f[21] = origin(tr.origin)
            // a pen entry's priming: never in the insulin columns, which stay the injected units
            val pen = penKeys(rec.penJson)
            if (pen != null && (tr.kind == TreatmentKind.RapidInsulin || tr.kind == TreatmentKind.LongInsulin)) {
                f[22] = tenths(pen.primed ?: 0.0)
            }
            lines += Line(tr.at, 1, tr.id, f)
        }
        lines.sortWith(compareBy<Line>({ it.t }, { it.order }, { it.id }))
        val gen = generatedAt.atOffset(ZoneOffset.UTC)
        val out = StringBuilder()
        out.append(
            "Glucose Data,Generated on,%04d-%02d-%02d %02d:%02d UTC,Generated by,Sukrara\r\n"
                .format(Locale.ROOT, gen.year, gen.monthValue, gen.dayOfMonth, gen.hour, gen.minute),
        )
        out.append(header(mmol).joinToString(",")).append("\r\n")
        for (l in lines) out.append(l.f.joinToString(",", transform = ::escape)).append("\r\n")
        return out.toString()
    }

    /** The readings that become rows: in [[from], [to]), oldest first, each ≥ [MIN_GAP_S] after the one before. */
    fun thin(
        readings: List<Reading>,
        from: Instant,
        to: Instant,
    ): List<Reading> {
        val out = ArrayList<Reading>()
        for (r in readings.sortedBy { it.t }) {
            if (r.t >= from && r.t < to && (out.isEmpty() || r.t.epochSecond - out.last().t.epochSecond >= MIN_GAP_S)) out += r
        }
        return out
    }

    /** `sukrara-glucose-2026-10-05-to-2026-10-19.csv`: the period only, never a name (share targets show it). */
    fun fileName(
        from: Instant,
        to: Instant,
        zone: ZoneId,
    ): String = "sukrara-glucose-${local(from, zone).take(10)}-to-${local(maxOf(from, to.minusSeconds(1)), zone).take(10)}.csv"

    /** One decimal, half away from zero, `.` whatever the locale. */
    internal fun tenths(x: Double): String {
        val n = abs(x * 10).roundToLong()
        return (if (x < 0 && n > 0) "-" else "") + "${n / 10}.${n % 10}"
    }

    internal fun escape(s: String): String =
        if (s.any { it == ',' || it == '"' || it == '\r' || it == '\n' }) "\"" + s.replace("\"", "\"\"") + "\"" else s

    internal fun textCell(s: String): String = if (s.isNotEmpty() && s[0] in "=+-@\t\r") "'$s" else s

    private fun origin(o: TreatmentOrigin) =
        when (o) {
            TreatmentOrigin.Phone -> "phone"
            TreatmentOrigin.Mac -> "mac"
            TreatmentOrigin.Follower -> "follower"
        }

    private class PenKeys(val primed: Double?)

    /** The pen keys of a stored entry (`pen` = the pen's serial marks a pen entry, `pr` = primed units). */
    private fun penKeys(json: String?): PenKeys? {
        val o = json?.let { runCatching { Json.parseToJsonElement(it) as? JsonObject }.getOrNull() } ?: return null
        (o["pen"] as? JsonPrimitive)?.contentOrNull ?: return null
        return PenKeys((o["pr"] as? JsonPrimitive)?.doubleOrNull)
    }

    private fun local(
        t: Instant,
        zone: ZoneId,
    ): String {
        val d = t.atZone(zone)
        return "%04d-%02d-%02d %02d:%02d".format(Locale.ROOT, d.year, d.monthValue, d.dayOfMonth, d.hour, d.minute)
    }

    private fun iso(
        t: Instant,
        zone: ZoneId,
    ): String {
        val d = t.atZone(zone)
        val off = d.offset.totalSeconds
        return "%04d-%02d-%02dT%02d:%02d:%02d%s%02d:%02d".format(
            Locale.ROOT,
            d.year,
            d.monthValue,
            d.dayOfMonth,
            d.hour,
            d.minute,
            d.second,
            if (off < 0) "-" else "+",
            abs(off) / 3600,
            abs(off) % 3600 / 60,
        )
    }
}
