import Foundation

/// Readings and treatments as one CSV in LibreView's "Glucose Data" layout, byte for byte what Android's
/// `GlucoseCsv.kt` writes (both run contracts/export). Tidepool Uploader's LibreView import reads it; four columns of
/// our own at the end: ISO 8601 time with offset, trend, who entered a treatment, a pen entry's primed units.
/// Pure: the save panel belongs to the app.
public enum GlucoseCsv {
    /// Readings closer than this (s) to the previous row are skipped (5-minute rows from 1-minute data).
    public static let minGap: Int64 = 280

    /// The sensor whose serial fills the column for rows inside its life.
    public struct Sensor: Sendable, Equatable {
        public var serial: String
        public var start: Int64
        public var end: Int64

        public init(serial: String, start: Int64, end: Int64) {
            self.serial = serial
            self.start = start
            self.end = end
        }
    }

    /// The 23 columns, in `unit`.
    public static func header(_ unit: GlucoseUnit) -> [String] {
        let u = unit.symbol
        return [
            "Device", "Serial Number", "Device Timestamp", "Record Type", "Historic Glucose \(u)", "Scan Glucose \(u)",
            "Non-numeric Rapid-Acting Insulin", "Rapid-Acting Insulin (units)", "Non-numeric Food",
            "Carbohydrates (grams)", "Carbohydrates (servings)", "Non-numeric Long-Acting Insulin",
            "Long-Acting Insulin (units)", "Notes", "Strip Glucose \(u)", "Ketone mmol/L", "Meal Insulin (units)",
            "Correction Insulin (units)", "User Change Insulin (units)", "Time (ISO 8601)", "Trend (mg/dL/min)",
            "Entered By", "Primed Insulin (units)",
        ]
    }

    /// The CSV for times in [from, to) (epoch s), CRLF line ends. Deleted treatments are skipped.
    public static func write(
        readings: [Reading], treatments: [Treatment], from: Int64, to: Int64, zone: TimeZone, generatedAt: Int64,
        sensor: Sensor? = nil, unit: GlucoseUnit = .mgdl
    ) -> String {
        func serial(_ t: Int64) -> String {
            guard let s = sensor, !s.serial.isEmpty, t >= s.start, t < s.end else { return "" }
            return s.serial
        }
        func row(_ t: Int64, _ type: String) -> [String] {
            var f = [String](repeating: "", count: 23)
            f[0] = "Sukrara"
            f[1] = serial(t)
            f[2] = local(t, zone)
            f[3] = type
            f[19] = iso(t, zone)
            return f
        }
        var lines: [(t: Int64, order: Int, id: String, f: [String])] = []
        var last: Int64?
        for r in readings.sorted(by: { $0.t < $1.t }) {
            let t = Int64(r.t.timeIntervalSince1970.rounded(.down))
            guard t >= from && t < to else { continue }
            if let l = last, t - l < minGap { continue }
            last = t
            var f = row(t, "0")
            f[4] = unit == .mmol ? tenths(Double(r.mgdl) / GlucoseUnit.mgdlPerMmol) : String(r.mgdl)
            f[20] = r.rate.map(tenths) ?? ""
            lines.append((t, 0, "", f))
        }
        for tr in treatments where !tr.del && tr.t >= from && tr.t < to {
            var f: [String]
            switch tr.k {
            case .rapid:
                f = row(tr.t, "4")
                f[7] = tenths(tr.a)
            case .long:
                f = row(tr.t, "4")
                f[12] = tenths(tr.a)
            case .carbs:
                f = row(tr.t, "5")
                f[9] = String(Int64(tr.a.rounded()))
            case .note:
                f = row(tr.t, "6")
            }
            f[13] = textCell(tr.n)
            f[21] = tr.o.rawValue
            // a pen entry's priming (0.0 = none); never in the insulin column
            if tr.fromPen { f[22] = tenths(tr.pr ?? 0) }
            lines.append((tr.t, 1, tr.id, f))
        }
        lines.sort { ($0.t, $0.order, $0.id) < ($1.t, $1.order, $1.id) }
        var out = "Glucose Data,Generated on,\(local(generatedAt, TimeZone(identifier: "UTC")!)) UTC,Generated by,Sukrara\r\n"
        out += header(unit).joined(separator: ",") + "\r\n"
        for l in lines { out += l.f.map(escape).joined(separator: ",") + "\r\n" }
        return out
    }

    /// `sukrara-glucose-2026-10-05-to-2026-10-19.csv`: the period only, never a name.
    public static func fileName(from: Int64, to: Int64, zone: TimeZone) -> String {
        "sukrara-glucose-\(local(from, zone).prefix(10))-to-\(local(max(from, to - 1), zone).prefix(10)).csv"
    }

    /// The export periods, in the order of the settings schema's `exportPeriod` options: this sensor (only when its
    /// start is known), the last 7 / 14 / 30 days, all time.
    public enum Period: String, Sendable, CaseIterable {
        case sensor, d7 = "7", d14 = "14", d30 = "30", all

        public var title: String {
            switch self {
            case .sensor: "This sensor"
            case .d7: "Last 7 days"
            case .d14: "Last 14 days"
            case .d30: "Last 30 days"
            case .all: "All time"
            }
        }

        /// [from, to) in epoch s at `now`, or nil (no sensor known). All time starts at the oldest entry held.
        public func range(now: Int64, sensor: Sensor?, oldest: Int64?) -> (from: Int64, to: Int64)? {
            let to = now + 1
            switch self {
            case .sensor:
                guard let s = sensor, s.start > 0 else { return nil }
                return (s.start, min(to, s.end + 1))
            case .d7: return (to - 7 * 86400, to)
            case .d14: return (to - 14 * 86400, to)
            case .d30: return (to - 30 * 86400, to)
            case .all: return (min(oldest ?? to - 86400, to - 1), to)
            }
        }

        /// The periods offered now (This sensor only with a known sensor).
        public static func offered(sensor: Sensor?) -> [Period] {
            allCases.filter { $0 != .sensor || (sensor?.start ?? 0) > 0 }
        }
    }

    /// One decimal, half away from zero, `.` whatever the locale.
    static func tenths(_ x: Double) -> String {
        let n = Int64((abs(x) * 10).rounded())
        return (x < 0 && n > 0 ? "-" : "") + "\(n / 10).\(n % 10)"
    }

    static func escape(_ s: String) -> String {
        s.contains(where: { $0 == "," || $0 == "\"" || $0 == "\r" || $0 == "\n" || $0 == "\r\n" })
            ? "\"" + s.replacingOccurrences(of: "\"", with: "\"\"") + "\"" : s
    }

    /// A note starting with a formula character gets a leading apostrophe (CSV injection in spreadsheets).
    static func textCell(_ s: String) -> String {
        guard let c = s.unicodeScalars.first, "=+-@\t\r".unicodeScalars.contains(c) else { return s }
        return "'" + s
    }

    private static func parts(_ t: Int64, _ zone: TimeZone) -> DateComponents {
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = zone
        return cal.dateComponents(
            [.year, .month, .day, .hour, .minute, .second], from: Date(timeIntervalSince1970: TimeInterval(t)))
    }

    private static func pad(_ v: Int?, _ w: Int = 2) -> String {
        let s = String(v ?? 0)
        return String(repeating: "0", count: max(0, w - s.count)) + s
    }

    private static func local(_ t: Int64, _ zone: TimeZone) -> String {
        let d = parts(t, zone)
        return "\(pad(d.year, 4))-\(pad(d.month))-\(pad(d.day)) \(pad(d.hour)):\(pad(d.minute))"
    }

    private static func iso(_ t: Int64, _ zone: TimeZone) -> String {
        let d = parts(t, zone)
        let off = zone.secondsFromGMT(for: Date(timeIntervalSince1970: TimeInterval(t)))
        return "\(pad(d.year, 4))-\(pad(d.month))-\(pad(d.day))T\(pad(d.hour)):\(pad(d.minute)):\(pad(d.second))"
            + "\(off < 0 ? "-" : "+")\(pad(abs(off) / 3600)):\(pad(abs(off) % 3600 / 60))"
    }
}
