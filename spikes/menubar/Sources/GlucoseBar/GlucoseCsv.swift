/// Readings and treatments as one CSV in LibreView's "Glucose Data" layout, byte for byte what Android's
/// `export/GlucoseCsv.kt` writes (rules there and in docs/22 "In Sukrara: CSV export"); both run spikes/export-fixtures
/// (`Sukrara -exportselftest`). Tidepool Uploader's LibreView import reads it; three columns of our own at the end
/// (ISO 8601 time with offset, trend, who entered a treatment).
enum GlucoseCsv {
    static let minGap: Int64 = 280
    private static let mgdlPerMmol = 18.0182

    struct Sensor { var serial: String; var start: Int64; var end: Int64 }
    struct Row { var t: Int64; var sgv: Int; var rate: Double? }

    static func header(mmol: Bool) -> [String] {
        let u = mmol ? "mmol/L" : "mg/dL"
        return ["Device", "Serial Number", "Device Timestamp", "Record Type", "Historic Glucose \(u)", "Scan Glucose \(u)",
                "Non-numeric Rapid-Acting Insulin", "Rapid-Acting Insulin (units)", "Non-numeric Food", "Carbohydrates (grams)",
                "Carbohydrates (servings)", "Non-numeric Long-Acting Insulin", "Long-Acting Insulin (units)", "Notes",
                "Strip Glucose \(u)", "Ketone mmol/L", "Meal Insulin (units)", "Correction Insulin (units)",
                "User Change Insulin (units)", "Time (ISO 8601)", "Trend (mg/dL/min)", "Entered By"]
    }

    /// The CSV for `t` in [from, to) (epoch s), CRLF line ends. Deleted treatments are skipped.
    static func write(readings: [Row], treatments: [Treatment], from: Int64, to: Int64, zone: TimeZone, generatedAt: Int64,
                      sensor: Sensor? = nil, mmol: Bool = false) -> String {
        func serial(_ t: Int64) -> String {
            guard let s = sensor, !s.serial.isEmpty, t >= s.start, t < s.end else { return "" }
            return s.serial
        }
        func base(_ t: Int64, _ type: String) -> [String] {
            var f = [String](repeating: "", count: 22)
            f[0] = "Sukrara"; f[1] = serial(t); f[2] = local(t, zone); f[3] = type; f[19] = iso(t, zone)
            return f
        }
        var lines: [(t: Int64, order: Int, id: String, f: [String])] = []
        var last: Int64?
        for r in readings.sorted(by: { $0.t < $1.t }) where r.t >= from && r.t < to {
            if let l = last, r.t - l < minGap { continue }
            last = r.t
            var f = base(r.t, "0")
            f[4] = mmol ? tenths(Double(r.sgv) / mgdlPerMmol) : String(r.sgv)
            f[20] = r.rate.map(tenths) ?? ""
            lines.append((r.t, 0, "", f))
        }
        for tr in treatments where !tr.del && tr.t >= from && tr.t < to {
            var f: [String]
            switch tr.k {
            case "rapid": f = base(tr.t, "4"); f[7] = tenths(tr.a)
            case "long": f = base(tr.t, "4"); f[12] = tenths(tr.a)
            case "carbs": f = base(tr.t, "5"); f[9] = String(Int64(tr.a.rounded()))
            default: f = base(tr.t, "6")
            }
            f[13] = textCell(tr.n); f[21] = tr.o
            lines.append((tr.t, 1, tr.id, f))
        }
        lines.sort { ($0.t, $0.order, $0.id) < ($1.t, $1.order, $1.id) }
        var out = "Glucose Data,Generated on,\(local(generatedAt, TimeZone(identifier: "UTC")!)) UTC,Generated by,Sukrara\r\n"
        out += header(mmol: mmol).joined(separator: ",") + "\r\n"
        for l in lines { out += l.f.map(escape).joined(separator: ",") + "\r\n" }
        return out
    }

    /// `sukrara-glucose-2026-10-05-to-2026-10-19.csv`: the period only, never a name.
    static func fileName(from: Int64, to: Int64, zone: TimeZone) -> String {
        "sukrara-glucose-\(local(from, zone).prefix(10))-to-\(local(max(from, to - 1), zone).prefix(10)).csv"
    }

    /// One decimal, half away from zero, `.` whatever the locale.
    static func tenths(_ x: Double) -> String {
        let n = Int64((abs(x) * 10).rounded())
        return (x < 0 && n > 0 ? "-" : "") + "\(n / 10).\(n % 10)"
    }

    static func escape(_ s: String) -> String {
        s.contains(where: { $0 == "," || $0 == "\"" || $0 == "\r" || $0 == "\n" || $0 == "\r\n" })
            ? "\"" + s.replacingOccurrences(of: "\"", with: "\"\"") + "\"" : s
    }

    static func textCell(_ s: String) -> String {
        guard let c = s.unicodeScalars.first, "=+-@\t\r".unicodeScalars.contains(c) else { return s }
        return "'" + s
    }

    private static func parts(_ t: Int64, _ zone: TimeZone) -> DateComponents {
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = zone
        return cal.dateComponents([.year, .month, .day, .hour, .minute, .second], from: Date(timeIntervalSince1970: TimeInterval(t)))
    }

    private static func pad(_ v: Int?, _ w: Int = 2) -> String {
        let s = String(v ?? 0)
        return String(repeating: "0", count: max(0, w - s.count)) + s
    }

    private static func local(_ t: Int64, _ zone: TimeZone) -> String {
        let d = parts(t, zone)
        return "\(pad(d.year, 4))-\(pad(d.month))-\(pad(d.day)) \(pad(d.hour)):\(pad(d.minute))"
    }

    private static func iso(_ t: Int64, _ zone: TimeZone) -> String {
        let d = parts(t, zone)
        let off = zone.secondsFromGMT(for: Date(timeIntervalSince1970: TimeInterval(t)))
        return "\(pad(d.year, 4))-\(pad(d.month))-\(pad(d.day))T\(pad(d.hour)):\(pad(d.minute)):\(pad(d.second))"
            + "\(off < 0 ? "-" : "+")\(pad(abs(off) / 3600)):\(pad(abs(off) % 3600 / 60))"
    }

    /// Glucose Report › Export…: the report's period as a CSV, through the save panel (HIG "File management").
    @MainActor static func save(days: Int, readings: [GraphReading], treatments: [Treatment]) {
        let to = Int64(Date().timeIntervalSince1970) + 1
        let from = to - Int64(days) * 86400
        let zone = TimeZone.current
        let panel = NSSavePanel()
        panel.allowedContentTypes = [.commaSeparatedText]
        panel.nameFieldStringValue = fileName(from: from, to: to, zone: zone)
        panel.canCreateDirectories = true
        guard panel.runModal() == .OK, let url = panel.url else { return }
        let csv = write(readings: readings.map { Row(t: Int64($0.t), sgv: $0.sgv, rate: $0.rate) }, treatments: treatments,
                        from: from, to: to, zone: zone, generatedAt: Int64(Date().timeIntervalSince1970))
        do {
            try csv.write(to: url, atomically: true, encoding: .utf8)
            log("export: \(url.lastPathComponent) (\(days) d)")
        } catch {
            let a = NSAlert(error: error)
            a.runModal()
        }
    }

    /// The shared cases (spikes/export-fixtures/*.json, the files Android's GlucoseCsvTest runs). Run from the repo.
    static func selfTest() -> Bool {
        var dir = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
        while !FileManager.default.fileExists(atPath: dir.appendingPathComponent("spikes/export-fixtures").path) {
            if dir.path == "/" { print("FAIL export fixtures: spikes/export-fixtures not found above the working directory"); return false }
            dir.deleteLastPathComponent()
        }
        dir.appendPathComponent("spikes/export-fixtures")
        var failures = 0, n = 0
        let files = ((try? FileManager.default.contentsOfDirectory(atPath: dir.path)) ?? []).filter { $0.hasSuffix(".json") }.sorted()
        for f in files {
            guard let data = FileManager.default.contents(atPath: dir.appendingPathComponent(f).path),
                  let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let cases = root["cases"] as? [[String: Any]] else { print("FAIL \(f): unreadable"); failures += 1; continue }
            for c in cases {
                let name = "\(f): \(c["name"] as? String ?? "?")"
                func i64(_ v: Any?) -> Int64 { (v as? NSNumber)?.int64Value ?? 0 }
                let readings = (c["readings"] as? [[String: Any]] ?? []).map {
                    Row(t: i64($0["t"]), sgv: Int(i64($0["sgv"])), rate: ($0["rate"] as? NSNumber)?.doubleValue)
                }
                let treatments = (c["treatments"] as? [[String: Any]] ?? []).map {
                    Treatment(id: $0["id"] as? String ?? "", k: $0["k"] as? String ?? "", a: ($0["a"] as? NSNumber)?.doubleValue ?? 0,
                              t: i64($0["t"]), n: $0["n"] as? String ?? "", u: 1, del: ($0["del"] as? Bool) ?? false, o: $0["o"] as? String ?? "")
                }
                let sensor = (c["sensor"] as? [String: Any]).map { Sensor(serial: $0["serial"] as? String ?? "", start: i64($0["start"]), end: i64($0["end"])) }
                let got = write(readings: readings, treatments: treatments, from: i64(c["from"]), to: i64(c["to"]),
                                zone: TimeZone(identifier: c["zone"] as? String ?? "UTC")!, generatedAt: i64(c["generated"]),
                                sensor: sensor, mmol: (c["mmol"] as? Bool) ?? false)
                let want = (c["expect"] as? [String] ?? []).map { $0 + "\r\n" }.joined()
                if got != want { print("FAIL \(name)\n--- want\n\(want)--- got\n\(got)"); failures += 1 }
                n += 1
            }
        }
        if n == 0 { print("FAIL export fixtures: no cases"); return false }
        print(failures == 0 ? "export fixtures: \(n) cases OK" : "export fixtures: \(failures) of \(n) FAILED")
        return failures == 0
    }
}
