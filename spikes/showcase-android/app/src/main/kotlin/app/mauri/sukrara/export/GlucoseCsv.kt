package app.mauri.sukrara.export

import app.mauri.sukrara.treatments.Treatment
import java.time.Instant
import java.time.ZoneId
import java.time.ZoneOffset
import kotlin.math.abs
import kotlin.math.roundToLong

/**
 * Readings and treatments as one CSV in LibreView's "Glucose Data" layout (docs/22 "In Sukrara: CSV export"): the
 * file Tidepool Uploader's LibreView import reads (`uploader/lib/drivers/abbott/libreViewDriver.js`) and Juggluco
 * writes (`Common/src/main/cpp/export/libreviewexport.cpp`), plus three columns of our own at the end (ISO 8601 time
 * with offset, trend, who entered a treatment), which index-based readers ignore. The Mac writes the same bytes
 * (spikes/menubar `GlucoseCsv.swift`); both run spikes/export-fixtures.
 *
 * - One row per reading, at most one every 5 minutes (≥ [MIN_GAP_S] apart): LibreView's "historic" rate, so a
 *   reader that counts rows as 5-minute samples (Tidepool's time in range) isn't skewed by the 1-minute stream.
 * - Rows are oldest first (Tidepool takes the last row as the newest); readings before treatments at the same time.
 * - Device Timestamp is local time without an offset (LibreView's own column, year first so it can't be read as
 *   month-day); "Time (ISO 8601)" carries the offset, so the repeated hour when the clocks go back stays apart.
 * - No person's name anywhere: "Generated by" is the app, "Entered By" is the device kind (phone | mac | follower).
 * - RFC 4180 quoting; a note that starts like a formula (= + - @) gets a leading `'` so a spreadsheet shows it as text.
 */
object GlucoseCsv {
    const val MIME = "text/csv"
    const val MIN_GAP_S = 280L
    private const val MGDL_PER_MMOL = 18.0182

    /**
     * [model]: the sensor's model when it isn't a Libre 3 (`core/SensorOutputs.model`, e.g. "Dexcom G7 / ONE+
     * (untested)"): its rows say "Sukrara · <model>" in Device. Null (the Libre 3, the Mac) keeps "Sukrara".
     */
    data class Sensor(val serial: String, val start: Long, val end: Long, val model: String? = null)
    data class Row(val t: Long, val sgv: Int, val rate: Double?)

    fun header(mmol: Boolean): List<String> {
        val u = if (mmol) "mmol/L" else "mg/dL"
        return listOf("Device", "Serial Number", "Device Timestamp", "Record Type", "Historic Glucose $u", "Scan Glucose $u",
            "Non-numeric Rapid-Acting Insulin", "Rapid-Acting Insulin (units)", "Non-numeric Food", "Carbohydrates (grams)",
            "Carbohydrates (servings)", "Non-numeric Long-Acting Insulin", "Long-Acting Insulin (units)", "Notes",
            "Strip Glucose $u", "Ketone mmol/L", "Meal Insulin (units)", "Correction Insulin (units)",
            "User Change Insulin (units)", "Time (ISO 8601)", "Trend (mg/dL/min)", "Entered By")
    }

    /** The CSV for `t` in [[from], [to]) (epoch s), CRLF line ends. Treatments include tombstones; they're skipped. */
    fun write(readings: List<Row>, treatments: List<Treatment>, from: Long, to: Long, zone: ZoneId, generatedAt: Long,
              sensor: Sensor? = null, mmol: Boolean = false): String {
        fun serial(t: Long) = sensor?.takeIf { it.serial.isNotEmpty() && t >= it.start && t < it.end }?.serial ?: ""
        fun device(t: Long) = sensor?.takeIf { it.model != null && t >= it.start && t < it.end }?.let { "Sukrara · ${it.model}" } ?: "Sukrara"
        fun base(t: Long, type: String) = Array(22) { "" }.also {
            it[0] = device(t); it[1] = serial(t); it[2] = local(t, zone); it[3] = type; it[19] = iso(t, zone)
        }
        class Line(val t: Long, val order: Int, val id: String, val f: Array<String>)
        val lines = ArrayList<Line>()
        for (r in thin(readings, from, to)) {
            lines += Line(r.t, 0, "", base(r.t, "0").also {
                it[4] = if (mmol) tenths(r.sgv / MGDL_PER_MMOL) else r.sgv.toString()
                it[20] = r.rate?.let(::tenths) ?: ""
            })
        }
        for (tr in treatments) {
            if (tr.del || tr.t < from || tr.t >= to) continue
            val f = when (tr.k) {
                "rapid" -> base(tr.t, "4").also { it[7] = tenths(tr.a) }
                "long" -> base(tr.t, "4").also { it[12] = tenths(tr.a) }
                "carbs" -> base(tr.t, "5").also { it[9] = Math.round(tr.a).toString() }
                else -> base(tr.t, "6")
            }
            f[13] = textCell(tr.n); f[21] = tr.o
            lines += Line(tr.t, 1, tr.id, f)
        }
        lines.sortWith(compareBy<Line>({ it.t }, { it.order }, { it.id }))
        val gen = Instant.ofEpochSecond(generatedAt).atOffset(ZoneOffset.UTC)
        val out = StringBuilder()
        out.append("Glucose Data,Generated on,%04d-%02d-%02d %02d:%02d UTC,Generated by,Sukrara\r\n"
            .format(java.util.Locale.ROOT, gen.year, gen.monthValue, gen.dayOfMonth, gen.hour, gen.minute))
        out.append(header(mmol).joinToString(",")).append("\r\n")
        for (l in lines) out.append(l.f.joinToString(",", transform = ::escape)).append("\r\n")
        return out.toString()
    }

    /** The readings that become rows: in [[from], [to]), oldest first, each ≥ [MIN_GAP_S] after the one before. */
    fun thin(readings: List<Row>, from: Long, to: Long): List<Row> {
        val out = ArrayList<Row>()
        for (r in readings.sortedBy { it.t }) if (r.t >= from && r.t < to && (out.isEmpty() || r.t - out.last().t >= MIN_GAP_S)) out += r
        return out
    }

    /** `sukrara-glucose-2026-10-05-to-2026-10-19.csv`: the period only, never a name (share targets show it). */
    fun fileName(from: Long, to: Long, zone: ZoneId): String =
        "sukrara-glucose-${local(from, zone).take(10)}-to-${local(maxOf(from, to - 1), zone).take(10)}.csv"

    /** One decimal, half away from zero, `.` whatever the locale. */
    internal fun tenths(x: Double): String {
        val n = abs(x * 10).roundToLong()
        return (if (x < 0 && n > 0) "-" else "") + "${n / 10}.${n % 10}"
    }

    internal fun escape(s: String): String =
        if (s.any { it == ',' || it == '"' || it == '\r' || it == '\n' }) "\"" + s.replace("\"", "\"\"") + "\"" else s

    internal fun textCell(s: String): String = if (s.isNotEmpty() && s[0] in "=+-@\t\r") "'$s" else s

    private fun local(t: Long, zone: ZoneId): String {
        val d = Instant.ofEpochSecond(t).atZone(zone)
        return "%04d-%02d-%02d %02d:%02d".format(java.util.Locale.ROOT, d.year, d.monthValue, d.dayOfMonth, d.hour, d.minute)
    }

    private fun iso(t: Long, zone: ZoneId): String {
        val d = Instant.ofEpochSecond(t).atZone(zone)
        val off = d.offset.totalSeconds
        return "%04d-%02d-%02dT%02d:%02d:%02d%s%02d:%02d".format(java.util.Locale.ROOT, d.year, d.monthValue, d.dayOfMonth,
            d.hour, d.minute, d.second, if (off < 0) "-" else "+", abs(off) / 3600, abs(off) % 3600 / 60)
    }
}
