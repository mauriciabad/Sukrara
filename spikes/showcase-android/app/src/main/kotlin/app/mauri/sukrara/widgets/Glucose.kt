package app.mauri.sukrara.widgets

import app.mauri.sukrara.R

import android.graphics.Color
import kotlin.math.abs
import kotlin.math.roundToInt

/** One sensor reading. [rate] is mg/dL per minute, null when the source has no trend. */
data class Reading(val epochSec: Long, val mgdl: Int, val rate: Double?) {
    fun ageSec(nowSec: Long) = nowSec - epochSec
    fun stale(nowSec: Long) = ageSec(nowSec) > STALE_AFTER_SEC

    companion object {
        const val STALE_AFTER_SEC = 5 * 60
    }
}

fun nowSec() = System.currentTimeMillis() / 1000

/** Same mapping as the Mac (spikes/menubar TrendArrow.swift): 0 → flat, ±3 mg/dL/min → vertical. */
object Trend {
    const val FULL_SCALE = 3.0

    /** Screen-space angle in degrees: -90 = straight up (rising fast), 0 = flat, +90 = down. */
    fun angleDeg(rate: Double): Float = (-(rate / FULL_SCALE).coerceIn(-1.0, 1.0) * 90).toFloat()

    /**
     * Glance can't rotate a view, so the continuous angle is quantised to the 5° steps of the pre-rendered
     * vector arrows (arrow_00 = up … arrow_18 = flat … arrow_36 = down; generated by the status-bar spike).
     */
    fun drawable(rate: Double?): Int = when {
        rate == null -> R.drawable.arrow_none
        rate >= FULL_SCALE -> R.drawable.arrow_up2
        rate <= -FULL_SCALE -> R.drawable.arrow_down2
        else -> ARROWS[((angleDeg(rate) + 90) / 5).roundToInt().coerceIn(0, 36)]
    }

    fun word(rate: Double?): String = when {
        rate == null -> "trend unknown"
        abs(rate) < 1 -> "steady"
        rate > 0 -> if (rate >= 2) "rising fast" else "rising"
        else -> if (rate <= -2) "falling fast" else "falling"
    }

    private val ARROWS = intArrayOf(
        R.drawable.arrow_00, R.drawable.arrow_01, R.drawable.arrow_02, R.drawable.arrow_03, R.drawable.arrow_04,
        R.drawable.arrow_05, R.drawable.arrow_06, R.drawable.arrow_07, R.drawable.arrow_08, R.drawable.arrow_09,
        R.drawable.arrow_10, R.drawable.arrow_11, R.drawable.arrow_12, R.drawable.arrow_13, R.drawable.arrow_14,
        R.drawable.arrow_15, R.drawable.arrow_16, R.drawable.arrow_17, R.drawable.arrow_18, R.drawable.arrow_19,
        R.drawable.arrow_20, R.drawable.arrow_21, R.drawable.arrow_22, R.drawable.arrow_23, R.drawable.arrow_24,
        R.drawable.arrow_25, R.drawable.arrow_26, R.drawable.arrow_27, R.drawable.arrow_28, R.drawable.arrow_29,
        R.drawable.arrow_30, R.drawable.arrow_31, R.drawable.arrow_32, R.drawable.arrow_33, R.drawable.arrow_34,
        R.drawable.arrow_35, R.drawable.arrow_36,
    )
}

/** The user's personal thresholds (same as the Mac app and the status-bar spike). */
object Range {
    const val LOW = 65
    const val SLIGHTLY_HIGH = 145
    const val HIGH = 185
    const val TARGET_LOW = 70
    const val TARGET_HIGH = 180

    /** The graphs' in-range band: the same thresholds [color] uses, so the band and the line colours agree. */
    const val BAND_LOW = LOW
    const val BAND_HIGH = HIGH

    val RED = Color.rgb(0xFF, 0x45, 0x3A)
    val ORANGE = Color.rgb(0xFF, 0x9F, 0x0A)

    /** null = in range, draw with the surface's default colour. */
    fun color(mgdl: Int): Int? = when {
        mgdl < LOW || mgdl > HIGH -> RED
        mgdl > SLIGHTLY_HIGH -> ORANGE
        else -> null
    }
}

/** "now", "3 min ago", "2 h ago". */
fun ageText(ageSec: Long): String = when {
    ageSec < 60 -> "now"
    ageSec < 3600 -> "${ageSec / 60} min ago"
    ageSec < 86_400 -> "${ageSec / 3600} h ago"
    else -> "${ageSec / 86_400} d ago"
}
