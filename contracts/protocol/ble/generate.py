# Writes default-mtu.json from the OGS draft-1 vectors (python3 -I generate.py > default-mtu.json): a wearer phone and
# a Mac follower that never exchanged MTUs (ATT MTU 23), exactly as both apps must frame it (ogs-ble B§4).
import json, os, struct

HERE = os.path.dirname(os.path.abspath(__file__))
OGS = json.load(open(os.path.join(HERE, "..", "ogs", "ogs-draft1.json")))
MTU = 23
ATTRIBUTE = 512
HEADER = 6


def compact(v):
    return json.dumps(v, separators=(",", ":"), ensure_ascii=False).encode()


def frames(msg_id, payload, per):
    count = max(1, -(-len(payload) // per))
    return [struct.pack(">HHH", msg_id, i, count) + payload[i * per:(i + 1) * per] for i in range(count)]


def write_frames(payload):
    # one ATT Write Request carries ATT_MTU - 3 bytes; a frame never needs a long (prepared) write
    return frames(1, payload, max(min(MTU - 3, ATTRIBUTE) - HEADER, 14))


hid = OGS["ble"]["hello_id"]
hello = compact(hid["hello"])
info = compact(["INFO", {"v": 2, "nonce": hid["nonce"], "m": OGS["ble"]["info_m"]["m"]}])
assert hid["nonce"] == OGS["ble"]["info_m"]["nonce"] and hid["sid"] == OGS["ble"]["info_m"]["sid"]

# What a central that sizes frames from CoreBluetooth's `.withResponse` length (512) sends: the whole HELLO in one
# frame, which the stack carries as Prepare Write requests of ATT_MTU - 5 bytes each, then Execute Write.
long_frame = frames(1, hello, ATTRIBUTE - HEADER)
assert len(long_frame) == 1 and len(long_frame[0]) > MTU - 3
part = MTU - 5
prepared = [{"offset": o, "value": long_frame[0][o:o + part].hex()} for o in range(0, len(long_frame[0]), part)]

out = {
    "about": "Android wearer <-> Mac follower over Bluetooth at the default ATT MTU 23 (no MTU exchange). Throwaway "
    "keys from the OGS draft-1 vectors (follower F on a mac). Generated by generate.py; read by Android "
    "NearbyServerCoreTest and Mac NearbyTests.",
    "att_mtu": MTU,
    "sid": hid["sid"],
    "follower": hid["follower"],
    "dev": hid["dev"],
    "nonce": hid["nonce"],
    "hello": hid["hello"],
    "hello_frames": [f.hex() for f in write_frames(hello)],
    "info": json.loads(info),
    "info_frames": [f.hex() for f in frames(1, info, max(min(MTU - 3, ATTRIBUTE) - HEADER, 14))],
    "long_write": {
        "about": "the same HELLO as one 512-capped frame, as Prepare Write parts (offset, value) then Execute Write: "
        "the wearer accepts it like the plain frames",
        "frame": long_frame[0].hex(),
        "prepared": prepared,
    },
    "expect": {"named": hid["follower"], "device": hid["dev"], "owner": "ours"},
}
assert all(len(bytes.fromhex(f)) <= MTU - 3 for f in out["hello_frames"] + out["info_frames"])
print(json.dumps(out, indent=2))
