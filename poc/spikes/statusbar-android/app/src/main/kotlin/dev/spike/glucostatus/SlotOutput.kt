package dev.spike.glucostatus

import android.annotation.SuppressLint
import android.content.Context
import android.util.Log
import java.io.BufferedReader
import java.io.Writer
import kotlin.math.roundToInt
import kotlinx.coroutines.flow.update

/**
 * Approach 3a: number + trend as *system icons* on the right of the status bar (next to Wi-Fi/battery),
 * via [SlotDaemon] running as root. SystemUI puts icons from outside SystemUI at the far left of the system
 * icons, newest first — so the trend is added first and ends up right of the number.
 */
class SlotOutput(private val context: Context) {
    private var proc: Process? = null
    private var stdin: Writer? = null
    private var stdout: BufferedReader? = null

    @Synchronized
    fun show(r: Reading) {
        // One resource per value (generated by tools/gen-slot-drawables.swift): the Compose status bar ignores
        // the icon level, so the app picks the drawable.
        val number = when {
            r.mgdl < 40 -> "sb_lo"
            r.mgdl > 400 -> "sb_hi"
            else -> "sb_n${r.mgdl}"
        }
        val trend = when {
            r.rate == null -> "sb_t_none"
            Trend.isDouble(r.rate) -> if (r.rate > 0) "sb_t_up2" else "sb_t_down2"
            else -> "sb_t%02d".format(((Trend.angleDeg(r.rate) + 90f) / 5f).roundToInt())
        }
        val desc = "Glucose ${r.mgdl} mg/dL ${Trend.arrow(r.rate)}"
        // New external icons are placed first (leftmost), so add the trend before the number.
        if (!send("set $SLOT_TREND ${res(trend)} 0 $desc")) return
        send("set $SLOT_NUMBER ${res(number)} 0 $desc")
    }

    @SuppressLint("DiscouragedApi")
    private fun res(name: String) = context.resources.getIdentifier(name, "drawable", context.packageName)

    @Synchronized
    fun stop() {
        runCatching { stdin?.close() } // daemon removes its icons on EOF
        proc?.destroy()
        proc = null; stdin = null; stdout = null
        Hub.state.update { it.copy(slot = "off") }
    }

    private fun send(cmd: String): Boolean {
        if (proc?.isAlive != true && !start()) return false
        return try {
            stdin!!.apply { write(cmd + "\n"); flush() }
            val reply = stdout!!.readLine() ?: "eof"
            Hub.state.update { it.copy(slot = "daemon: $reply") }
            reply == "ok"
        } catch (e: Exception) {
            Log.w(TAG, "slot daemon", e)
            stop()
            Hub.state.update { it.copy(slot = "daemon died: ${e.message}") }
            false
        }
    }

    private fun start(): Boolean = try {
        val apk = context.applicationInfo.sourceDir
        val cmd = "CLASSPATH=$apk exec app_process /system/bin ${SlotDaemon::class.java.name} ${context.packageName}"
        val p = ProcessBuilder("su", "-c", cmd).redirectErrorStream(true).start()
        proc = p
        stdin = p.outputStream.writer()
        stdout = p.inputStream.bufferedReader()
        val hello = stdout!!.readLine()
        Hub.state.update { it.copy(slot = "daemon: $hello") }
        if (hello?.startsWith("ready") != true) { stop(); false } else true
    } catch (e: Exception) {
        // No su binary, or KernelSU hasn't granted root to this app.
        Hub.state.update { it.copy(slot = "no root: ${e.message}") }
        false
    }

    companion object {
        const val SLOT_NUMBER = "glucose"
        const val SLOT_TREND = "glucose_trend"
    }
}
